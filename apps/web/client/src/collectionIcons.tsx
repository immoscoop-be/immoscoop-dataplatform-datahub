/** `building-estate` → `Building estate`. */
export function iconLabel(name: IconName): string {
  const words = name.replaceAll('-', ' ');
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/** The icon of a Collection, as a line icon in the colour of the text around it. */
export function CollectionIcon({ name, size = 18 }: { name: IconName; size?: number }) {
  const Drawn = ICONS[name];
  return <Drawn size={size} stroke={2} aria-hidden="true" focusable="false" />;
}
