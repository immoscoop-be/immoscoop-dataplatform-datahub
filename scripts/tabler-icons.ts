/**
 * Generate the list of icons a Collection can carry, from Tabler Icons (DEC-CO-14).
 *
 * Usage:
 *   node scripts/tabler-icons.ts   # rewrite packages/contracts/src/tablerIcons.ts
 *
 * Also available as `pnpm icons:build`. Run it after upgrading `@tabler/icons` in packages/contracts, and
 * commit the result: catalogue checks icons against this list, and the web app copies their
 * drawings and searches it. A test fails while the list and the installed version differ. It uses
 * only Node built-ins and runs directly on Node 24, which strips the TypeScript types itself.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const TABLER = path.join(ROOT, 'packages/contracts/node_modules/@tabler/icons');
const OUT = path.join(ROOT, 'packages/contracts/src/tablerIcons.ts');

interface TablerIcon {
  name: string;
  category?: string;
  tags?: (string | number)[];
}

const { version } = JSON.parse(readFileSync(path.join(TABLER, 'package.json'), 'utf8')) as { version: string };
const index = JSON.parse(readFileSync(path.join(TABLER, 'icons.json'), 'utf8')) as Record<string, TablerIcon>;

// The logos of brands are other companies' trademarks, not a picture of a functional domain.
const icons = Object.values(index)
  .filter((icon) => icon.category !== 'Brand')
  .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
const categoryOf = (icon: TablerIcon): string => icon.category || 'Other';
const categories = [...new Set(icons.map(categoryOf))].sort();

const rows = icons.map((icon) => {
  // The words of the name are found anyway; keep only what Tabler adds to them.
  const own = new Set(icon.name.split('-'));
  const words = [...new Set((icon.tags ?? []).map((tag) => String(tag).toLowerCase().trim()))].filter((word) => word && !own.has(word));
  return `  ${JSON.stringify([icon.name, categories.indexOf(categoryOf(icon)), words.join(' ')])},`;
});

writeFileSync(
  OUT,
  [
    `// Generated by \`pnpm icons:build\` (scripts/tabler-icons.ts) from @tabler/icons ${version}. Do not edit by hand.`,
    '',
    '/** The version of Tabler Icons the list below comes from. */',
    `export const TABLER_ICONS_VERSION = ${JSON.stringify(version)};`,
    '',
    "/** Tabler's categories, which the icons below point to by their place in this list. */",
    'export const TABLER_CATEGORIES: readonly string[] = [',
    ...categories.map((category) => `  ${JSON.stringify(category)},`),
    '];',
    '',
    '/**',
    ' * Every outline icon of Tabler Icons but the logos of brands (DEC-CO-14), by name: its category,',
    ' * and the words Tabler gives it beyond those of its name, to search by.',
    ' */',
    'export const TABLER_ICONS: readonly (readonly [name: string, category: number, words: string])[] = [',
    ...rows,
    '];',
    '',
  ].join('\n'),
);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${icons.length} icons in ${categories.length} categories of Tabler Icons ${version}`);
