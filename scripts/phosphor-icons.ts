/**
 * Generate the list of icons a Collection can carry, from Phosphor (DEC-CO-19).
 *
 * Usage:
 *   node scripts/phosphor-icons.ts   # rewrite packages/contracts/src/phosphorIcons.ts
 *
 * Also available as `pnpm icons:build`. Run it after upgrading `@phosphor-icons/core` in
 * packages/contracts, and commit the result: catalogue checks icons against this list, and the web
 * app searches it and shows their drawings. A test fails while the list and the installed version
 * differ. It uses only Node built-ins: the catalogue of Phosphor is data in its package, loaded from
 * its file as it is. It runs directly on Node 24, which strips the TypeScript types itself.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = path.resolve(import.meta.dirname, '..');
const PHOSPHOR = path.join(ROOT, 'packages/contracts/node_modules/@phosphor-icons/core');
const OUT = path.join(ROOT, 'packages/contracts/src/phosphorIcons.ts');

interface PhosphorIcon {
  name: string;
  alias?: { name: string };
  categories: readonly string[];
  tags: readonly string[];
}

const { version } = JSON.parse(readFileSync(path.join(PHOSPHOR, 'package.json'), 'utf8')) as { version: string };
const { icons: index } = (await import(pathToFileURL(path.join(PHOSPHOR, 'dist/index.mjs')).href)) as { icons: readonly PhosphorIcon[] };

// The logos of brands are other companies' trademarks, not a picture of a functional domain.
const icons = index.filter((icon) => !icon.categories.includes('brands')).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

const rows = icons.map((icon) => {
  // The words of the name are found anyway; keep only what Phosphor adds to them. A tag such as
  // `*new*` marks a release, not the icon; a former name is a word to find it by.
  const own = new Set(icon.name.split('-'));
  const tags = [...(icon.alias ? [icon.alias.name.replaceAll('-', ' ')] : []), ...icon.tags];
  const words = [...new Set(tags.filter((tag) => !tag.startsWith('*')).flatMap((tag) => tag.toLowerCase().split(/\s+/)))].filter((word) => word && !own.has(word));
  return `  ${JSON.stringify([icon.name, words.join(' ')])},`;
});

writeFileSync(
  OUT,
  [
    `// Generated by \`pnpm icons:build\` (scripts/phosphor-icons.ts) from @phosphor-icons/core ${version}. Do not edit by hand.`,
    '',
    '/** The version of Phosphor the list below comes from. */',
    `export const PHOSPHOR_ICONS_VERSION = ${JSON.stringify(version)};`,
    '',
    '/**',
    ' * Every icon of Phosphor but the logos of brands (DEC-CO-19), by name, with the words Phosphor',
    ' * gives it beyond those of its name, to search by.',
    ' */',
    'export const PHOSPHOR_ICONS: readonly (readonly [name: string, words: string])[] = [',
    ...rows,
    '];',
    '',
  ].join('\n'),
);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${icons.length} icons of Phosphor ${version}`);
